-- SafeMove: tabelas no Oracle (gerado pelo Hibernate a partir das classes de backend/.../model).
-- A aplicação cria/atualiza as tabelas sozinha (spring.jpa.hibernate.ddl-auto=update);
-- este script serve para o DER e para criar o banco manualmente, se preferir.
--
-- Se existirem tabelas de uma versão anterior (sem a coluna id_usuario em ocorrencias), apague antes:
-- DROP TABLE confirmacoes_ocorrencia CASCADE CONSTRAINTS;
-- DROP TABLE ocorrencias CASCADE CONSTRAINTS;
-- DROP TABLE incidentes CASCADE CONSTRAINTS;
-- DROP TABLE perfis_usuario CASCADE CONSTRAINTS;

    create table confirmacoes_ocorrencia (
        criado_em timestamp(9) with time zone not null,
        id_confirmacao number(19,0) generated by default as identity,
        id_ocorrencia number(19,0) not null,
        id_usuario varchar2(128 char) not null,
        primary key (id_confirmacao),
        constraint uk_confirmacao_ocorr_usuario unique (id_ocorrencia, id_usuario)
    );

    create table incidentes (
        atraso number(10,0),
        gravidade number(10,0) not null,
        lat binary_double not null,
        lng binary_double not null,
        atualizado_em timestamp(9) with time zone not null,
        id_incidente number(19,0) generated by default as identity,
        categoria varchar2(30 char) not null check ((categoria in ('ACIDENTE','CONGESTIONAMENTO','VIA_INTERDITADA','FAIXA_INTERDITADA','OBRAS','ALAGAMENTO','PERIGO','VEICULO_QUEBRADO','CHUVA','NEBLINA','VENTO','GELO','DESCONHECIDO'))),
        id_tomtom varchar2(128 char) not null unique,
        descricao varchar2(500 char),
        via varchar2(255 char),
        primary key (id_incidente)
    );

    create table ocorrencias (
        confirmacoes number(10,0) not null,
        lat binary_double not null,
        lng binary_double not null,
        criado_em timestamp(9) with time zone not null,
        id_ocorrencia number(19,0) generated by default as identity,
        tipo varchar2(30 char) not null check ((tipo in ('ASSALTO','BURACO','ACIDENTE','ALAGAMENTO','TRANSITO','ILUMINACAO'))),
        id_usuario varchar2(128 char) not null,
        descricao varchar2(500 char),
        primary key (id_ocorrencia)
    );

    create table perfis_usuario (
        criado_em timestamp(9) with time zone not null,
        nome varchar2(120 char) not null,
        id_usuario varchar2(128 char) not null,
        email varchar2(254 char) not null unique,
        primary key (id_usuario)
    );

    create index ix_incidentes_lat_lng 
       on incidentes (lat, lng);

    create index ix_ocorrencias_lat_lng 
       on ocorrencias (lat, lng);

    alter table confirmacoes_ocorrencia 
       add constraint fk_confirmacao_ocorrencia 
       foreign key (id_ocorrencia) 
       references ocorrencias;

    alter table confirmacoes_ocorrencia 
       add constraint fk_confirmacao_usuario 
       foreign key (id_usuario) 
       references perfis_usuario;

    alter table ocorrencias 
       add constraint fk_ocorrencia_usuario 
       foreign key (id_usuario) 
       references perfis_usuario;
